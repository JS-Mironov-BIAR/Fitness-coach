// Сборка готового промпта под конкретного клиента из данных его анкеты.
type Lead = Record<string, unknown>;

function v(l: Lead, k: string, fb = "не указано"): string {
  const x = l[k];
  if (x === null || x === undefined || String(x).trim() === "") return fb;
  return String(x).trim();
}

export function buildTrainingPrompt(l: Lead): string {
  return `Действуй как опытный специалист по физической подготовке. Пиши на русском, конкретно и строго по структуре в конце ответа. Без вступлений, извинений и общих фраз — только польза. Если каких-то данных не хватает — сделай разумные допущения и отметь их. Работай по принципу «не навреди».

Данные клиента:
- Имя: ${v(l, "name")}
- Пол: ${v(l, "sex")}
- Возраст: ${v(l, "age")}
- Рост / вес: ${v(l, "height_cm")} см / ${v(l, "weight_kg")} кг (желаемый вес: ${v(l, "target_weight_kg")})
- Цель: ${v(l, "goal")} (срок: ${v(l, "goal_term")})
- Уровень: ${v(l, "experience")}, стаж: ${v(l, "training_years")}
- Где занимается: ${v(l, "place")}; инвентарь: ${v(l, "equipment")}
- Дней в неделю: ${v(l, "days_per_week")}; минут на занятие: ${v(l, "session_minutes")}
- Ограничения по здоровью: ${v(l, "health_limitations")}
- Цикл / самочувствие: ${v(l, "cycle_notes")}; беременность/ГВ: ${v(l, "pregnancy")}
- Сейчас занимается: ${v(l, "current_program")}
- Что не получается / плато: ${v(l, "stuck_points")}
- Что уже пробовала: ${v(l, "tried")}

Составь программу занятий с учётом ограничений. Обязательные правила:
1. «Не навреди»: ничего, что перегружает проблемные зоны.
2. Большой вес / боли в коленях или пояснице → чередование «верх/низ», без ударной нагрузки; отдельно укрепление коленей и поясницы.
3. Остеохондроз / проблемы позвоночника → без весов на плечах и осевой нагрузки, только изолированные упражнения.
4. Форма ягодиц без роста бёдер → первым упражнением ягодичный мостик.
5. Зажим шеи / «голова в плечах» → раскрытие грудного отдела и разминка шеи; низ тела в поддерживающем режиме.
6. Варикоз → завершать МФР-прокаткой ног и растяжкой для лимфотока.
7. Каждое занятие завершается МФР + растяжкой.
8. Домашнее задание между занятиями под ограничение клиента.
9. Мягкие формулировки, без давления и стеснения.

Формат ответа: логика программы (2–3 предложения) → программа по дням (упражнение · подходы×повторы · примечание по технике) → финальный блок МФР + растяжка → домашнее задание → красные флаги.`;
}

export function buildNutritionPrompt(l: Lead): string {
  return `Действуй как опытный нутрициолог. Пиши на русском, конкретно и строго по структуре в конце ответа. Без вступлений и общих фраз — только польза. Если каких-то данных не хватает — сделай разумные допущения и отметь их.

Данные клиента:
- Имя: ${v(l, "name")}
- Пол: ${v(l, "sex")}; возраст: ${v(l, "age")}
- Рост / вес: ${v(l, "height_cm")} см / ${v(l, "weight_kg")} кг (желаемый вес: ${v(l, "target_weight_kg")})
- Цель: ${v(l, "goal")}
- Характер работы: ${v(l, "work_type")}; бытовая активность: ${v(l, "daily_activity")}; сон: ${v(l, "sleep")}
- Аллергии / непереносимости: ${v(l, "allergies")}
- Предпочтения / что не ест: ${v(l, "food_prefs")}
- Приёмов пищи в день: ${v(l, "meals_per_day")}; бюджет: ${v(l, "food_budget")} BYN / ${v(l, "food_budget_period", "неделя")}
- Предпочтения в еде (любит / не любит): ${v(l, "food_prefs")}
- Опыт диет: ${v(l, "diet_experience")}

Жёсткие правила по продуктам (соблюдай строго):
- Крупы — только рис и гречка. НЕ используй пшено, булгур и другие крупы. Не используй куриные голени и куриные сердца.
- В каждый день обязательно включай базу: картошка, рис, гречка, яйца, зефир.
- Мясо: куриная ветчина (сухая, без сала). Если цель — набор массы, добавь свинину и говядину. Если цель — сушка/похудение, только куриное филе, говядину исключи.
- Учитывай предпочтения клиента: что не любит — не используй, что любит — включай чаще.

Составь план питания на 7 дней:
– Завтрак, обед, ужин и перекус на каждый день с учётом предпочтений и бюджета (в BYN на указанный период)
– Калории и БЖУ каждого приёма пищи
– Список покупок на неделю с примерной стоимостью
– Правило на случай срыва
Формулировки мягкие, без жёстких запретов и обещаний «волшебного похудения».`;
}
